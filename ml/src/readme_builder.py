from __future__ import annotations

import json
import shutil
from pathlib import Path

# ============================== BRANDING ======================================
CLIENT_NAME = "XYZ"
PROJECT_TITLE = "AI Crop Recommendation System"
TAGLINE = (
    "A trained, validated and packaged machine-learning model that recommends "
    "suitable crops from soil nutrients and local climate conditions."
)
AUTHOR = "Muhammad Aun"
AUTHOR_URL = "https://aun.abcodify.com"
# ==============================================================================

MARK = "<!-- generated by ml/src/readme_builder.py: edit the constants at the top of that file, not this README -->"


def _f(x: float) -> str:
    return f"{x:.3f}"


def _gain(new: float, old: float) -> str:
    d = new - old
    if abs(d) < 0.0005:
        return "0.000"
    return f"{'+' if d > 0 else '-'}{abs(d):.3f}"


def _img(path: str | None, alt: str) -> str:
    return f'<img src="{path}" alt="{alt}" width="100%">' if path else ""


def _grid(items: list[tuple[str, str | None]]) -> list[str]:
    """Two-column image table; each item is (caption, image path)."""
    items = [(c, p) for c, p in items if p]
    out = ["<table>"]
    for i in range(0, len(items), 2):
        pair = items[i : i + 2]
        out.append("<tr>")
        for cap, p in pair:
            out.append(
                f'<td width="50%" valign="top"><b>{cap}</b><br>{_img(p, cap)}</td>'
            )
        if len(pair) == 1:
            out.append("<td></td>")
        out.append("</tr>")
    out.append("</table>")
    return out


def build(index: dict, root: Path) -> None:
    mods = index["modules"]
    date = index["generated_at"][:10]
    L: list[str] = [
        MARK,
        "",
        '<div align="center">',
        "",
        f"# {PROJECT_TITLE}",
        "",
        f"**{TAGLINE}**",
        "",
        (
            "![Python](https://img.shields.io/badge/Python-3.10%2B-1b5e20?logo=python&logoColor=white) "
            "![scikit-learn](https://img.shields.io/badge/scikit--learn-pipelines-2e7d32?logo=scikitlearn&logoColor=white) "
            "![XGBoost](https://img.shields.io/badge/XGBoost-ensembles-388e3c) "
            "![Status](https://img.shields.io/badge/status-delivered-43a047)"
        ),
        "",
        f"Prepared for **{CLIENT_NAME}** &nbsp;·&nbsp; Delivered by [{AUTHOR}]({AUTHOR_URL}) &nbsp;·&nbsp; {date}",
        "",
        "</div>",
        "",
    ]
    if index.get("overview_figure"):
        L += [
            '<p align="center">',
            f'  <img src="{index["overview_figure"]}" alt="Results overview" width="90%">',
            "</p>",
            "",
        ]

    # ---- overview
    L += [
        "## Overview",
        "",
        (
            f"This repository contains the machine-learning layer delivered to {CLIENT_NAME}: "
            f"{len(mods)} model module{'s' if len(mods) != 1 else ''} that read the CSV data in `ml/data/raw`, "
            "validate and clean it, train and compare several algorithms, and publish ready-to-load model packages "
            "together with an evaluation report. One command refreshes everything, including this document."
        ),
        "",
        "| Module | What it does | Data source |",
        "|---|---|---|",
    ]
    L += [f"| **{m['title']}** | {m['description']} | {m['source']} |" for m in mods]
    L += [
        "",
        "## Results at a glance",
        "",
        (
            "All figures are measured on a held-out test set that is used once, after the model has been selected. "
            "The reference column is a straightforward baseline trained on the same data and split."
        ),
        "",
        "| Module | Target | Delivered model | Accuracy | Macro-F1 | Reference macro-F1 | Gain |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in mods:
        for t in m["targets"]:
            L.append(
                f"| {m['title']} | {t['target']} | {t['selected_model']} | {_f(t['test']['accuracy'])} | "
                f"**{_f(t['test']['macro_f1'])}** | {_f(t['baseline']['macro_f1'])} | "
                f"{_gain(t['test']['macro_f1'], t['baseline']['macro_f1'])} |"
            )
    L += [
        "",
        (
            "> Macro-F1 averages the F1 score of every class equally, so a model cannot look good by only predicting the "
            "most common label."
        ),
        "",
    ]

    # ---- modules
    for n, m in enumerate(mods, 1):
        L += ["---", "", f"## {n}. {m['title']}", "", m["description"], ""]
        for t in m["targets"]:
            L += [
                f"### Target: `{t['target']}`",
                "",
                (
                    f"- **Records:** {t['rows']:,} labelled &nbsp;|&nbsp; **Classes:** {t['n_classes']} ({', '.join(t['classes'][:12])}"
                    f"{'…' if t['n_classes'] > 12 else ''})"
                ),
                f"- **Evaluation split:** {t['split']} (train {t['n_train']:,} / validation {t['n_val']:,} / test {t['n_test']:,})"
                + (
                    f", reports from {t['date_range'][0]} to {t['date_range'][1]}"
                    if t.get("date_range")
                    else ""
                ),
                f"- **Delivered model:** {t['selected_model']} (chosen on {t['selection_metric']}: {_f(t['selection_score'])})",
                f"- **Reference:** {t['baseline']['name']}",
                "",
                "| Metric | Reference | Delivered |",
                "|---|---|---|",
            ]
            for k, lab in (
                ("accuracy", "Accuracy"),
                ("macro_precision", "Macro precision"),
                ("macro_recall", "Macro recall"),
                ("macro_f1", "Macro-F1"),
                ("weighted_f1", "Weighted-F1"),
            ):
                L.append(f"| {lab} | {_f(t['baseline'][k])} | **{_f(t['test'][k])}** |")
            L.append(
                f"| Test mistakes | {t['baseline']['errors']} / {t['baseline']['n']} | **{t['test']['errors']} / {t['test']['n']}** |"
            )
            L.append("")
            f = t["figures"]
            L += _grid(
                [
                    ("Model comparison", f.get("selection")),
                    ("Feature distributions", f.get("eda_distributions")),
                    ("Confusion matrix", f.get("confusion")),
                    ("Per-class precision / recall / F1", f.get("per_class")),
                    ("Label distribution", f.get("class_distribution")),
                    ("Crop profiles", f.get("eda_profiles")),
                    ("Label mix over time", f.get("drift")),
                    ("Feature importance", f.get("importance")),
                    ("EDA – Feature Correlation Heatmap ", f.get("correlation")),
                ]
            )
            L.append("")
            if t["n_classes"] <= 8:
                L += [
                    "| Class | Precision | Recall | F1 | Test support |",
                    "|---|---|---|---|---|",
                ]
                L += [
                    f"| {p['label']} | {_f(p['precision'])} | {_f(p['recall'])} | {_f(p['f1'])} | {p['support']} |"
                    for p in t["per_class"]
                ]
                L.append("")
            else:
                weakest = sorted(t["per_class"], key=lambda p: p["f1"])[:5]
                L += [
                    "Weakest classes on the test set: "
                    + ", ".join(f"{p['label']} (F1 {_f(p['f1'])})" for p in weakest)
                    + ".",
                    "",
                ]
            if t["top_confusions"]:
                L += [
                    "Most frequent confusions: "
                    + "; ".join(
                        f"{a} → {b} ({c})" for c, a, b in t["top_confusions"][:3]
                    )
                    + ".",
                    "",
                ]
            ex = t["example"]
            L += [
                "<details><summary>Example: first record of the held-out test set (not hand-picked)</summary>",
                "",
                "```json",
                json.dumps(
                    {
                        "input": ex["input"],
                        "prediction": ex["output"],
                        "actual": ex["true"],
                    },
                    indent=2,
                    ensure_ascii=False,
                ),
                "```",
                "",
                "</details>",
                "",
            ]

    # ---- approach
    L += [
        "---",
        "",
        "## How it works",
        "",
        (
            "1. **Automatic discovery.** Every CSV in `ml/data/raw` is matched to a dataset profile by its column names. "
            "Unrecognised or unsuitable files are skipped, with the reason printed."
        ),
        (
            "2. **Validation and cleaning.** Empty reports, duplicate IDs and rare labels are removed, and inconsistent label "
            "names are normalised (for example legacy Bugzilla severities are grouped into S1-S2 / S3 / S4)."
        ),
        (
            "3. **Leakage control.** Only information available when a report is filed is used as input. Fields set during "
            "triage or fixing (status, resolution, fix time, assignee) are excluded."
        ),
        (
            "4. **Honest evaluation.** Data with timestamps is split chronologically; the test set is touched once, after "
            "model selection. Accuracy is reported with a 95% confidence interval."
        ),
        (
            "5. **Model search.** Several algorithm families are tuned by cross-validation on the training split, optimising "
            "macro-F1 with balanced class weights. A voting ensemble is delivered only when it beats the best single model."
        ),
        (
            "6. **Packaging.** The final model is refit on all labelled rows and saved as one bundle (model, class names, "
            "metadata). The previous version is archived, never overwritten."
        ),
        "",
        "## Repository structure",
        "",
        "```text",
        "ml/",
        "├── data/raw/                 input CSV files (any number)",
        "├── src/",
        "│   ├── train_all.py          discovery, training, evaluation, packaging",
        "│   ├── inference.py          load a model bundle and predict",
        "│   └── readme_builder.py     regenerates this README from measured results",
        "├── artifacts/",
        "│   ├── model.joblib          current model bundle",
        "│   ├── metrics.json          metrics, parameters and split details",
        "│   └── archive/              previous versions",
        "├── reports/",
        "│   ├── figures/              charts shown above",
        "│   └── results.md            full per-class results",
        "└── requirements.txt",
        "```",
        "",
        "## Quick start",
        "",
        "```bash",
        "python -m venv .venv",
        "source .venv/bin/activate          # Windows: .venv\\Scripts\\activate",
        "pip install -r ml/requirements.txt",
        "# place the CSV files in ml/data/raw/",
        "python ml/src/train_all.py",
        "```",
        "",
        "Retrain a single module with `ML_ONLY=ui_bug_triage python ml/src/train_all.py` "
        "(module keys: " + ", ".join(f"`{m['key']}`" for m in mods) + "). "
        "Set `ML_QUICK=1` for a fast smoke test.",
        "",
        "## Using the models",
        "",
        "```python",
        "import sys",
        'sys.path.append("ml/src")',
        "from inference import load_bundle, predict_bug, predict_crop",
        "",
    ]
    shown = False
    for m in mods:
        t = m["targets"][0]
        if m["kind"] == "text" and not shown:
            L += [
                f'bundle = load_bundle("{t["artifact"]}")',
                "predict_bug(bundle, "
                + ", ".join(
                    f"{k}={json.dumps(v, ensure_ascii=False)}"
                    for k, v in list(t["example"]["input"].items())[:3]
                )
                + ")",
                '# -> {"label": ..., "confidence": ..., "alternatives": [...], "model_version": ...}',
                "",
            ]
            shown = True
    for m in mods:
        if m["kind"] == "tabular":
            t = m["targets"][0]
            L += [
                f'crop = load_bundle("{t["artifact"]}")',
                "predict_crop(crop, "
                + ", ".join(f"{k}={v:g}" for k, v in t["example"]["input"].items())
                + ")",
                '# -> [{"label": ..., "confidence": ...}, ...]  (top 3)',
                "",
            ]
            break
    L += ["```", ""]

    # ---- validation notes
    notes = [
        (f"{m['title']} / {t['target']}", s)
        for m in mods
        for t in m["targets"]
        for s in t["notes"]
    ]
    skipped = index.get("skipped", [])
    if notes or skipped:
        L += ["## Validation notes", ""]
        L += [f"- **{who}:** {s}" for who, s in notes]
        L += [f"- `{s['file']}` {s['reason']}" for s in skipped]
        L += [
            "",
            (
                "Before connecting a model to live traffic, re-run `train_all.py` on a recent export of the production data "
                "and check the per-class results above for the classes that matter most to the business."
            ),
            "",
        ]
    L += [
        "---",
        "",
        f'<div align="center">Built by <a href="{AUTHOR_URL}">{AUTHOR}</a> · {AUTHOR_URL.replace("https://", "")}</div>',
        "",
    ]

    out = root / "README.md"
    if out.exists() and MARK not in out.read_text(encoding="utf-8", errors="ignore"):
        shutil.copy(out, root / "README.previous.md")
    out.write_text("\n".join(L), encoding="utf-8")
